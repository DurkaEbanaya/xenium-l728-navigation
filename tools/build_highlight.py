#!/usr/bin/env python3
"""Build an offline L728 highlight-settings candidate from verified v0.3.0."""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import argparse

ROOT = Path(__file__).resolve().parents[1]
BASE = 0x88000000
VERIFIED = "41aba70fd84346095a756ccc97dcbb33b23dcca4c9dba686351622c93f1a7f34"
PHONE_VERIFIED = "34a2d7ab0a09ea41faabd5b232d25f0a8e6dbc8dcd01eeb3aa4bd41625d8b41c"
FOLDER = ROOT / "experimental/highlight"
HOOKS = {0x1ed5c4: ("highlight_image", "2de9fc4116460446"),
         0x1ed668: ("highlight_string", "70b50d0004460cd0"),
         0x40a0c: ("highlight_font", "022806d0032804d0")}
CALLS = {0x6c6126: ("highlight_menu_text", 0x880a328e),
         0x6c7b46: ("highlight_menu_text", 0x880a328e),
         0x6c60c6: ("highlight_menu_scroll", 0x880a34cc),
         0x6c7aec: ("highlight_menu_scroll", 0x880a34cc)}


def thumb_bl(address, target):
    delta = (target & ~1) - (address + 4)
    if delta & 1 or not -(1 << 24) <= delta < (1 << 24):
        raise RuntimeError("Thumb BL out of range")
    s, i1, i2 = (delta >> 24) & 1, (delta >> 23) & 1, (delta >> 22) & 1
    return struct.pack("<HH", 0xf000 | (s << 10) | ((delta >> 12) & 0x3ff),
                       0xd000 | ((1 ^ i1 ^ s) << 13) | ((1 ^ i2 ^ s) << 11) | ((delta >> 1) & 0x7ff))


def sha(data):
    return hashlib.sha256(data).hexdigest()


def assets(source):
    # Preserve the stock selected bar's sabm nine-slice wrapper. Plain BMP
    # goes through the non-stretch draw path and is clipped to one pixel wide.
    wrapper = bytes.fromhex("7361626d0801010000010090")
    colors = [0x041f, 0xffe0, 0x07e0, 0xffff, 0xfd20, 0xf800, 0]
    images = []
    for color in colors[1:]:
        pixels = (struct.pack("<H", color) + b"\0\0") * 144
        image = (struct.pack("<2sIHHI", b"BM", 66+len(pixels),0,0,66) +
                 struct.pack("<IiiHHIIiiII",40,1,144,1,16,3,len(pixels),0,0,0,0) +
                 struct.pack("<III",0xf800,0x07e0,0x001f) + pixels)
        images.append(wrapper + image)
    def text(name, value):
        units = struct.unpack(f"<{len(value)+1}H", (value+"\0").encode("utf-16-le"))
        return f"static const uint16_t {name}[] = {{{','.join(map(str,units))}}};\n"
    out = "/* Generated by build_highlight.py. */\n#define BG_COUNT 7\n#define FG_COUNT 4\n"
    for name, value in (("label_bg","Фон выделения"),("label_fg","Буквы выделения"),
                        ("label_sample","Пример"),("label_unsaved","Не сохранено"),
                        ("highlight_path",r"D:\l728-highlight.cfg")):
        out += text(name,value)
    for category,names in (("bg",["Стандартный","Жёлтый","Зелёный","Белый","Оранжевый","Красный","Чёрный"]),
                           ("fg",["Стандартные","Чёрные","Белые","Жёлтые"])):
        for i,name in enumerate(names): out += text(f"{category}_{i}",name)
        out += f"static const uint16_t *const {category}_names[] = {{" + ",".join(
            f"{category}_{i}" for i in range(len(names))) + "};\n"
    out += "static const uint16_t bg_colors[] = {"+",".join(map(str,colors))+"};\n"
    out += "static const uint16_t fg_colors[] = {0,65535,65504};\n"
    out += f"static const uint8_t bg_images[6][{len(images[0])}] = {{\n" + ",\n".join(
        "{"+",".join(map(str,image))+"}" for image in images) + "};\n"
    (FOLDER / "highlight_assets.h").write_text(out)
    words = list(struct.unpack("<122I", source[0x3dd898:0x3dda80]))
    assert words[1] == 0x8831af25 and words[-1] == 0xf030
    words = words[:-1]
    # Callback is emitted as a symbol relocation rather than a numeric word.
    rows = [0xf110,1,0,0x9fe01,0x901d5, 0xf10a,1,0,0x9fe02,0x9fe01,
            0xf10e,1,0x9fe03,0x9fe01,
            0xf110,1,0,0x9fe04,0x901d5, 0xf10a,1,0,0x9fe05,0x9fe04,
            0xf10e,1,0x9fe06,0x9fe04,
            0xf110,1,0,0x9fe07,0x901d5, 0xf10a,1,0,0x9fe08,0x9fe07,
            0xf10f,1,0x9fe09,0x9fe07]
    for value in (0x9fe01,0x9fe02,0x9fe03,0x9fe04,0x9fe05,0x9fe06,0x9fe07,0x9fe08,0x9fe09,0x9fe0e):
        if struct.pack("<I",value) in source: raise RuntimeError("New control ID collision")
    descriptor = ".syntax unified\n.thumb\n.section .rodata\n.balign 4\n.global highlight_descriptor\nhighlight_descriptor:\n"
    for i,word in enumerate(words):
        descriptor += ".word highlight_display\n" if i == 1 else f".word {word:#x}\n"
    descriptor += "".join(f".word {word:#x}\n" for word in rows)
    descriptor += ".word highlight_preview\n.word 0xf030\n"
    (FOLDER / "descriptor.s").write_text(descriptor)


def main():
    # Only image construction needs pyelftools. Ready-package validation also
    # imports this module and must work with the standard-library-only Python
    # used by sudo.
    from elftools.elf.elffile import ELFFile

    global FOLDER
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--folder", type=Path, default=FOLDER)
    args = parser.parse_args()
    FOLDER = args.folder.resolve()
    if (FOLDER / "transition/plan.json").exists():
        raise RuntimeError("Do not overwrite an existing transition package; choose a new --folder")
    source = (ROOT / "experimental/sos-no-flash/l728-user-sos-CANDIDATE.bin").read_bytes()
    if sha(source) != VERIFIED: raise RuntimeError("Wrong installed source image")
    end = struct.unpack_from("<I",source,0x30)[0]+0x200
    offset = (end+15)&~15
    if source[end:] != b"\xff"*(len(source)-end): raise RuntimeError("Occupied payload tail")
    FOLDER.mkdir(exist_ok=True)
    assets(source)
    elf = FOLDER / "highlight.elf"
    subprocess.run(["clang","--target=armv7a-none-eabi","-mcpu=cortex-a7","-mthumb","-Oz",
        "-ffreestanding","-fno-builtin","-mno-unaligned-access","-mfpu=none","-mfloat-abi=soft","-Wall","-Wextra","-Werror",
        "-nostdlib","-fuse-ld=lld",f"-I{FOLDER}",f"-Wl,-T,{ROOT / 'tools/highlight.ld'}",
        f"-Wl,--defsym,PAYLOAD_ADDRESS={BASE+offset}", str(ROOT / "tools/highlight.c"),
        str(ROOT / "tools/highlight.s"),str(FOLDER / "descriptor.s"),"-o",str(elf)],check=True)
    subprocess.run(["objcopy","-O","binary","-j",".payload",str(elf),str(FOLDER / "highlight.bin")],check=True)
    with elf.open("rb") as stream:
        e = ELFFile(stream)
        symbols = {s.name:s["st_value"] for s in e.get_section_by_name(".symtab").iter_symbols() if s.name}
    payload = (FOLDER / "highlight.bin").read_bytes()
    length = (offset+len(payload)+2047)&~2047
    if length > 0x800000: raise RuntimeError("Payload crosses 8 MiB boundary")
    patched = bytearray(source+b"\xff"*(length-len(source)))
    patched[offset:offset+len(payload)] = payload
    struct.pack_into("<I",patched,0x30,offset+len(payload)-0x200)
    modifications = []
    for address,(name,original) in HOOKS.items():
        if source[address:address+8].hex() != original:
            raise RuntimeError(f"Unexpected hook {address:#x}: {source[address:address+8].hex()}")
        value = bytes.fromhex("dff800f0")+struct.pack("<I",symbols[name])
        patched[address:address+8] = value
        modifications.append({"offset":address,"original":original,"replacement":value.hex()})
    for address, (name, target) in CALLS.items():
        original = thumb_bl(BASE + address, target)
        if source[address:address+4] != original:
            raise RuntimeError(f"Unexpected menu call {address:#x}")
        value = thumb_bl(BASE + address, symbols[name])
        patched[address:address+4] = value
        modifications.append({"offset":address,"original":original.hex(),"replacement":value.hex()})
    if source[0x31be64:0x31be68] != struct.pack("<I",0x883dd898): raise RuntimeError("Wrong display pointer")
    struct.pack_into("<I",patched,0x31be64,symbols["highlight_descriptor"])
    old = source+b"\xff"*(length-len(source))
    pages = [p for p in range(length//2048) if old[p*2048:(p+1)*2048] != patched[p*2048:(p+1)*2048]]
    report = {"status":"OFFLINE CANDIDATE; DEVICE VALIDATION PENDING",
        "release":"v0.4.0", "phone_verified_sha256":PHONE_VERIFIED,
        "matches_phone_verified_image":sha(patched) == PHONE_VERIFIED,
        "owner_confirmation":"Работает идеально",
        "allocator_entry_mode":"ARM",
        "safe_to_flash":False,"device_accessed":False,"source_sha256":VERIFIED,
        "output_sha256":sha(patched),"source_bytes":len(source),"output_bytes":len(patched),
        "payload_offset":offset,"payload_bytes":len(payload),"hooks":modifications,
        "display_pointer_offset":0x31be64,"symbols":symbols,
        "changed_pages":[{"user_page":p,"physical_page":0x4f40+p,"block":(0x4f40+p)//64,
                          "page_in_block":(0x4f40+p)%64} for p in pages],
        "pending":["Run focused execution checks for this exact image",
                   "Check UI, persistence, menu font coverage on phone",
                   "Fresh readback and BootROM ECC validation before any NAND write"]}
    (FOLDER / "l728-user-highlight-CANDIDATE.bin").write_bytes(patched)
    (FOLDER / "manifest.json").write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({k:v for k,v in report.items() if k != "symbols"},indent=2))


if __name__ == "__main__": main()
